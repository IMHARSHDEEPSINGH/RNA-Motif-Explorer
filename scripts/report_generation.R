# -----------------------------------------------------------------------------
# export_motif_table_csv
# Exports the full motif ranking table to CSV.
# -----------------------------------------------------------------------------
export_motif_table_csv <- function(motif_table, out_path) {
  df_clean <- motif_table %>%
    select(
      kmer, total_count, seq_count, seq_frequency,
      observed_freq, expected_freq, enrichment_score,
      p_value, p_adjusted, significant,
      rank_freq, rank_enrichment, rank_significance, combined_rank
    ) %>%
    mutate(across(where(is.numeric), ~round(.x, 6)))

  write.csv(df_clean, file = out_path, row.names = FALSE)
  invisible(out_path)
}

# -----------------------------------------------------------------------------
# export_stats_csv
# Exports per-sequence statistics to CSV.
# -----------------------------------------------------------------------------
export_stats_csv <- function(per_seq_stats, out_path) {
  df_clean <- per_seq_stats %>%
    mutate(across(where(is.numeric), ~round(.x, 4)))

  write.csv(df_clean, file = out_path, row.names = FALSE)
  invisible(out_path)
}

# -----------------------------------------------------------------------------
# export_positional_csv
# Exports positional distribution data to CSV.
# -----------------------------------------------------------------------------
export_positional_csv <- function(pos_dist, out_path) {
  if (is.null(pos_dist) || nrow(pos_dist) == 0) {
    write.csv(data.frame(message = "No positional data available"),
              file = out_path, row.names = FALSE)
    return(invisible(out_path))
  }

  df_clean <- pos_dist %>%
    mutate(across(where(is.numeric), ~round(.x, 4)))

  write.csv(df_clean, file = out_path, row.names = FALSE)
  invisible(out_path)
}

# -----------------------------------------------------------------------------
# save_plot_png
# Saves a ggplot to PNG with consistent dimensions.
# -----------------------------------------------------------------------------
save_plot_png <- function(plot_obj, out_path,
                            width = 10, height = 6, dpi = 150) {
  if (is.null(plot_obj)) {
    warning("Cannot save NULL plot.")
    return(invisible(NULL))
  }
  ggsave(out_path, plot = plot_obj, width = width, height = height,
         dpi = dpi, bg = "#0D1117")
  invisible(out_path)
}

