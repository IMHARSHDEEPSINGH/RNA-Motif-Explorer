# -----------------------------------------------------------------------------
# prepare_all_downloads
# Bundles all export files, returns named list of file paths.
# -----------------------------------------------------------------------------
prepare_all_downloads <- function(motif_result, preproc_result,
                                   out_dir = "outputs") {
  dir.create(file.path(out_dir, "reports"), showWarnings = FALSE,
             recursive = TRUE)

  paths <- list()

  # Motif table CSV
  paths$motif_csv <- file.path(out_dir, "reports", "motif_table.csv")
  export_motif_table_csv(motif_result$motif_table, paths$motif_csv)

  # Sequence stats CSV
  paths$stats_csv <- file.path(out_dir, "reports", "sequence_stats.csv")
  export_stats_csv(preproc_result$stats$per_sequence, paths$stats_csv)

  # Positional distribution CSV
  paths$pos_csv <- file.path(out_dir, "reports", "positional_distribution.csv")
  export_positional_csv(motif_result$positional_dist, paths$pos_csv)

  paths
}
